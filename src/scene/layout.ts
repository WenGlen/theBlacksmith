/**
 * 爐前的鏡頭。
 *
 * 兩個條件一起決定的：
 *   1. 不能站在插入方向的同一條線上，否則料正對鏡頭縮成一個點，
 *      看不出推進去多深 —— 而深淺正是這個工位唯一要判斷的事
 *   2. 第一人稱是**自己左手拿著料**，所以料要從畫面左下角伸進火裡
 *      （Glen 2026-11-07 第三輪）
 *
 * 條件寫成向量：設 B 是「從火心指回手邊」的方向，鏡頭偏移是 (dx, dz)，
 * 則 B·(dx,dz) > 0（料朝鏡頭來，所以近端在畫面下方），
 * 且 B·right < 0（近端偏左），其中 right = (dz, 0, −dx) 正規化。
 * 第一次把 right 的符號寫反，結果料從右下伸進去，剛好相反。
 *
 * 光是方向對還不夠：手邊那一端**全程**都要待在畫面下方。
 * 推到底的時候它離火心最近，很容易浮到中線以上（量過：第三輪的擺位
 * 會跑到 y=359，畫面高 859）。解法是把視線抬高（看火心上方 0.2 m）
 * 並且把鏡頭往料的來向多退一點，讓透視把近端壓下去。
 * 現在這組量到的是 y 643 → 524，全程在下三分之一。
 */
export const FORGE_EYE: [number, number, number] = [-0.26, 1.2, -1.03];
