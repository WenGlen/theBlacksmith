/**
 * 技藝等級，以及它換算出來的判定寬度。
 *
 * 這個檔案存在的理由是 Glen 2026-11-08 第五輪回饋：
 * 「未來加入等級或技能相關的機制，讓這個判定範圍越來越寬，不然沒有成長感」。
 *
 * 所以判定寬度不准散在各處寫死，一律從這裡的 `level` 推出來。
 * 現在 `level` 是一個固定值，之後接等級表或技能樹時，
 * 要改的只有誰去寫 `SKILL.level`，底下這三個數字的算法不用動。
 */

/** 等級換算出來的瞄準參數 */
export interface AimSkill {
  /**
   * 落點往「按下點」收斂的比例 0..1。
   *
   * 0 = 放開在哪就打在哪（第 0 刀的行為）；
   * 1 = 放開在哪都打在按下的那一點，等於不用瞄。
   *
   * 這個數字同時做兩件事：放開時的誤差被原諒掉這個比例，
   * 而且落點預覽跟著游標走的速度也降到 (1 - assist)，
   * 也就是「判定變寬」與「靈敏度變低」是同一件事的兩面。
   */
  assist: number;
  /** 技藝本身的隨機散布半徑，單位是畫面寬度的比例 */
  scatterR: number;
  /** 游標可以超出工件兩端多少（佔全長比例）還算打在料上 */
  endSlack: number;
}

/**
 * 現在的技藝等級 0..1。
 *
 * 還沒有等級系統，先當成「學徒」固定在 0。
 * 要試手感可以在主控台改 `__rig.session` 之外直接改這個物件。
 */
export const SKILL = { level: 0 };

/**
 * 共用的那一份，`aimSkill()` 每次呼叫就就地改寫它。
 *
 * 這是為了遵守「每幀不配置新物件」那條規矩：落點預覽每幀都要讀判定寬度，
 * 每次回傳一個新物件等於每秒丟 60 個垃圾給 GC。
 * 代價是**不准把回傳值存起來**，要用就當場讀完。
 */
const CURRENT: AimSkill = { assist: 0, scatterR: 0, endSlack: 0 };

/**
 * 把 0..1 的等級換成判定寬度。
 * @returns 共用物件，當場讀完，不要存起來
 */
export function aimSkill(level: number = SKILL.level): AimSkill {
  const L = Math.max(0, Math.min(1, level));
  Object.assign(CURRENT, {
    // 學徒就已經原諒一半以上的誤差。第 0 刀是 0，實測太硬（Glen 第五輪）
    assist: 0.55 + 0.3 * L,
    // 散布圈隨等級縮小，這是「越練越準」看得見的那一半
    scatterR: 0.009 - 0.006 * L,
    // 兩端的寬限也隨等級變大，老師傅比較不會打到砧面上
    endSlack: 0.08 + 0.1 * L,
  });
  return CURRENT;
}
